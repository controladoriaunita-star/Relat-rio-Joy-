-- Mesmas tabelas do ESQUEMA_SQLITE em backend/app/db.py.
-- O acesso é só pelo backend (conexão Postgres direta). O RLS fica ativo sem
-- policies para que nenhuma tabela seja exposta pela API pública do Supabase.

create table if not exists public.perfis (
    usuario_id uuid primary key references auth.users (id) on delete cascade,
    email text not null,
    nome text not null,
    perfil text not null,
    ativo integer not null default 1,
    criado_em text not null
);

create table if not exists public.setores (
    id bigint generated by default as identity primary key,
    codigo text not null unique,
    nome text not null,
    ordem integer not null default 0,
    ativo integer not null default 1
);

create table if not exists public.linhas_projecao (
    id bigint generated by default as identity primary key,
    setor_id bigint not null references public.setores (id),
    nome text not null,
    rubrica text not null,
    ordem integer not null default 0,
    ativo integer not null default 1,
    unique (setor_id, nome)
);

create table if not exists public.projecoes (
    linha_id bigint not null references public.linhas_projecao (id),
    mes text not null,
    valor double precision not null,
    atualizado_por text,
    atualizado_em text,
    primary key (linha_id, mes)
);

create table if not exists public.depara (
    fonte text not null,
    chave text not null,
    concat text not null,
    classificacao text not null,
    atualizado_por text,
    atualizado_em text,
    primary key (fonte, chave)
);

create table if not exists public.saldos (
    id bigint generated by default as identity primary key,
    empresa integer not null,
    conta text not null,
    descricao text,
    data text not null,
    saldo double precision not null,
    unique (empresa, conta, data)
);

create table if not exists public.parametros (
    chave text primary key,
    valor text not null
);

create table if not exists public.cargas (
    id bigint generated by default as identity primary key,
    fonte text not null,
    origem text not null,
    iniciado_em text not null,
    duracao_s double precision,
    status text not null,
    linhas integer,
    mensagem text,
    dados text
);
create index if not exists ix_cargas_fonte on public.cargas (fonte, id);

create table if not exists public.historico (
    id bigint generated by default as identity primary key,
    quando text not null,
    usuario text,
    acao text not null,
    detalhe text
);

create table if not exists public.controle (
    id integer primary key check (id = 1),
    versao bigint not null
);
insert into public.controle (id, versao) values (1, 0) on conflict (id) do nothing;

