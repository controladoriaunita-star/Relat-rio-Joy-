-- Relatório de Aporte · Joy+ — login Microsoft 365 e envio do Resumo por e-mail.
--
-- tokens_microsoft: refresh token (cifrado pelo app) de quem entrou com a Microsoft; é o que
--   permite mandar o e-mail pela caixa do próprio usuário (escopo delegado Mail.Send).
-- destinatarios_email: e-mails já usados em cada obra, para marcar de novo nos próximos envios.
-- A permissão "resumo.enviar" é criada pelo próprio app ao iniciar (admin e diretor).
-- Rode ANTES de publicar a versão com login Microsoft. Pode ser rodada mais de uma vez.

begin;

create table if not exists public.tokens_microsoft (
    usuario_id    text primary key,
    refresh_token text not null,
    atualizado_em text not null
);
alter table public.tokens_microsoft enable row level security;   -- sem policies: só o backend lê

create table if not exists public.destinatarios_email (
    id           bigint generated by default as identity primary key,
    obra         text not null references public.obras (codigo),
    email        text not null,
    criado_por   text,
    criado_em    text not null,
    ultimo_envio text,
    unique (obra, email)
);
alter table public.destinatarios_email enable row level security;

commit;
